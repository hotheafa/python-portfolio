# Because it is considered a false value, it will print
print (bool(""))
# Because it will print zero (False)
print (bool(0))
#Because it's a decimal number, but it has the same value as zero, it will print false.
print (bool(0.0))
#Because it's text due to the presence of two quotation marks, True will print
print (bool("False"))
#Because it's text due to the presence of quotation marks, even if it contains zeros, because everything inside the quotation marks is text and will be printed as True.
print (bool("0"))

